function applyDict(dict: Record<string,string>) {
  // Mirror every key onto tr so all lookup styles resolve:
  //   tr.Settings, tr["New Chat"], tr.dict["New Chat"], t("New Chat")
  for (const k in dict) {
    if (Object.prototype.hasOwnProperty.call(dict, k)) {
      tr[k] = dict[k];
    }
  }
  tr.dict = dict;
  // Russian language name is always shown in Cyrillic
  tr.dict['Русский'] = 'Русский';
  tr['Русский'] = 'Русский';
}

function applyCode(code: string) {
  // Full dicts are embedded in this bundle — the single source of truth.
  // (lang/*.json is the editable reference; run scripts/sync-embedded-dicts.mjs
  // after editing it, then rebuild.)
  if (code === 'de') applyDict(DE_FULL);
  else if (code === 'ru') applyDict(RU_FULL);
  else if (code === 'es') applyDict(ES_FULL);
  else if (code === 'fr') applyDict(FR_FULL);
  else applyDict(EN_FULL);
}

if (browser) {
  const saved = (localStorage.getItem('lang') || 'en').trim();
  applyCode(saved);

  // Listen for runtime language changes from the settings dropdown
  window.addEventListener('storage', (e) => {
    if (e.key === 'lang' && e.newValue) applyCode(e.newValue.trim());
  });
  // Poll as fallback (storage events don't fire on same tab)
  let _last = saved;
  setInterval(() => {
    const cur = (localStorage.getItem('lang') || 'en').trim();
    if (cur !== _last) { _last = cur; applyCode(cur); }
  }, 500);
}

export function t(key: string): string {
  return tr.dict[key] || key;
}

export function applyLang(code: string) {
  localStorage.setItem('lang', code);
  applyCode(code.trim());
}

function applyDict(dict: Record<string,string>) {
  // Set each key directly on tr — same mechanism as tr.Settings = "Einstellungen"
  for (const k in dict) {
    if (dict.hasOwnProperty(k)) tr[k] = dict[k];
  }
  // Also set on tr.dict for t() function compatibility
  tr.dict = dict;
  tr["Русский"] = "Русский";
}

